"""Generate the iOS cursor constants from the shared header.

Both clients read the same measurements; the desktop includes the header directly,
iOS gets this generated Swift file. Running it is part of the build script, so the
two ends cannot drift: change the header, regenerate, and the phone follows.
"""
import pathlib
import re

ROOT = pathlib.Path(r"C:\Users\Mayn\Documents\deepseek-harness\default-workspace\crossdesk")
HEADER = ROOT / "libs/wire/include/remote_cursor_metrics.h"
OUTPUT = ROOT / "apps/ios/CrossDeskMobile/CursorMetrics.generated.swift"

text = HEADER.read_text(encoding="utf-8")

boxes = {}
for match in re.finditer(
    r"\{\s*(k[A-Za-z]+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", text
):
    name, x, y, w, h = match.group(1), *(int(match.group(i)) for i in range(2, 6))
    if name in boxes:      # the duplicate guards in the header
        continue
    boxes[name] = (x, y, w, h)

centred = set(re.findall(r"k[A-Za-z]+", re.search(
    r"kCentredShapes\{\{(.*?)\}\}", text, re.S).group(1)))

shape_numbers = {}
for match in re.finditer(r"^\s*(k[A-Za-z]+)\s*=\s*(\d+),", text, re.M):
    shape_numbers[match.group(1)] = int(match.group(2))

tile = float(re.search(r"kStandardTilePoints = ([\d.]+)f", text).group(1))
small = float(re.search(r"kSmallTilePoints = ([\d.]+)f", text).group(1))
large = float(re.search(r"kLargeTilePoints = ([\d.]+)f", text).group(1))
canvas = int(re.search(r"kCanvas = (\d+)", text).group(1))

lines = [
    "//",
    "// Generated by scripts/generate_cursor_metrics.py — do not edit by hand.",
    "// Source of truth: libs/wire/include/remote_cursor_metrics.h",
    "//",
    "// The same measurements drive the desktop overlay, so the pointer geometry",
    "// cannot drift between the two clients.",
    "//",
    "import CoreGraphics",
    "",
    "enum CursorMetrics {",
    f"    static let canvas: CGFloat = {canvas}",
    f"    static let defaultTile: CGFloat = {tile}",
    f"    static let smallTile: CGFloat = {small}",
    f"    static let standardTile: CGFloat = {tile}",
    f"    static let largeTile: CGFloat = {large}",
    "",
    "    /// Visible bounding box of the glyph inside the 64 px canvas (measured).",
    "    static func visibleBox(for shape: Int) -> CGRect {",
    "        switch shape {",
]

def swift_key(name: str) -> str:
    return shape_numbers[name]

by_shape = {}
for name, box in boxes.items():
    by_shape.setdefault(shape_numbers[name], box)

for shape in sorted(by_shape):
    x, y, w, h = by_shape[shape]
    lines.append(
        f"        case {shape}: return CGRect(x: {x}, y: {y}, width: {w}, height: {h})"
    )

lines += [
    f"        default: return CGRect(x: {by_shape[0][0]}, y: {by_shape[0][1]},"
    f" width: {by_shape[0][2]}, height: {by_shape[0][3]})",
    "        }",
    "    }",
    "",
    "    /// Hotspot inside the canvas: the tip for pointers, the centre otherwise.",
    "    static func hotspot(for shape: Int, tile: CGFloat) -> CGPoint {",
    "        let unit = tile / canvas",
    "        let box = visibleBox(for: shape)",
    f"        let centred: Set<Int> = {sorted(shape_numbers[s] for s in centred if s in shape_numbers)}",
    "        if centred.contains(shape) {",
    "            return CGPoint(x: (box.origin.x + box.width / 2) * unit,",
    "                           y: (box.origin.y + box.height / 2) * unit)",
    "        }",
    "        return CGPoint(x: box.origin.x * unit, y: box.origin.y * unit)",
    "    }",
    "}",
    "",
]

OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(lines)} lines)")
print("boxes:", {shape_numbers[k]: v for k, v in boxes.items()})
print("centred:", sorted(shape_numbers[s] for s in centred if s in shape_numbers))
print("tiles:", small, tile, large)
