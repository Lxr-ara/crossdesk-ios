"""Emit the bottom-bar geometry as its own generated Swift file.

Kept separate from the cursor generator so the two stay readable: the cursor file is
about pointer art, this one about the control bar. Both read the same header.

Measured from UU's iOS assets (com.netease.uuremote 4.48.1):
    icon_tool_*        24 x 24 pt
    icon_tool_hover_*  40 x 40 pt
"""
import pathlib
import re

ROOT = pathlib.Path(r"C:\Users\Mayn\Documents\deepseek-harness\default-workspace\crossdesk")
HEADER = ROOT / "libs/wire/include/remote_cursor_metrics.h"
OUTPUT = ROOT / "apps/ios/CrossDeskMobile/BarMetrics.generated.swift"

KEYS = [
    ("kBarIconPoints", "barIcon"),
    ("kBarTargetPoints", "barTarget"),
    ("kBarHeightPoints", "barHeight"),
    ("kBarItemGapPoints", "barGap"),
    ("kBarCornerPoints", "barCorner"),
    ("kBarEdgeInsetPoints", "barInset"),
    ("kBarChevronPoints", "barChevron"),
]

header = HEADER.read_text(encoding="utf-8")

block = (
    "\n// ---------------------------------------------------------------------------\n"
    "// 底部控制条的几何：来自 UU 的 iOS 资源实测（icon_tool_* 24 pt 画布、\n"
    "// icon_tool_hover_* 40 pt 触摸目标）。条高与间距由此推出，桌面端共用同一组值。\n"
    "// ---------------------------------------------------------------------------\n"
    + "".join(f"inline constexpr float {name} = {value}.0f;\n" for name, value in [
        ("kBarIconPoints", 24), ("kBarTargetPoints", 40), ("kBarHeightPoints", 56),
        ("kBarItemGapPoints", 8), ("kBarCornerPoints", 28), ("kBarEdgeInsetPoints", 12),
        ("kBarChevronPoints", 9),
    ])
)
if "kBarIconPoints" not in header:
    marker = "\n}  // namespace cursor_metrics"
    assert marker in header, "namespace close not found"
    header = header.replace(marker, block + marker, 1)
    HEADER.write_text(header, encoding="utf-8")
    print("header: bar geometry appended")

header = HEADER.read_text(encoding="utf-8")
values = {}
for key, _swift in KEYS:
    match = re.search(rf"{key} = ([\d.]+)f", header)
    assert match, f"{key} missing from the header"
    values[key] = match.group(1)

lines = [
    "//",
    "// Generated by scripts/generate_bar_metrics.py — do not edit by hand.",
    "// Source of truth: libs/wire/include/remote_cursor_metrics.h",
    "//",
    "import CoreGraphics",
    "",
    "enum BarMetrics {",
]
for key, swift in KEYS:
    lines.append(f"    static let {swift}: CGFloat = {values[key]}")
lines += ["}", ""]

OUTPUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUTPUT.relative_to(ROOT)}")
print({k: values[k] for k, _ in KEYS})
